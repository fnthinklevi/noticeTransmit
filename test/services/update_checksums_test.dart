import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:notice_transmit/services/update_checksums.dart';

/// 兜底源校验清单：`sha256sums.txt` 的地址合成与解析。
///
/// 这一组守的是一条很贵的静默失败：`version.json` 的 sha256 是按**本地构建**
/// 回填的，而 GitHub 兜底源上的包由 **CI 构建**；两个文件不是逐字节相同
/// （2026-11-21 实测 v1.6.7 arm64 差 97 字节）⇒ 拿 CDN 的 sha 判兜底包，
/// 正常下载会被 N3 判成"损坏"并删除，而这条只在 CDN 挂掉时才走到。
void main() {
  const direct =
      'https://github.com/fnthinklevi/noticeTransmit/releases/download/v1.6.7/'
      'notice_arm64_1.6.7+167.apk';
  const mirror =
      'https://xget.fnthink.top/gh/fnthinklevi/noticeTransmit/releases/download/'
      'v1.6.7/notice_arm64_1.6.7+167.apk';
  const hash =
      '0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef';

  group('清单地址：与 APK 同目录，只换最后一段', () {
    test('GitHub 直链与 xget 镜像都推出同一个 Release 下的清单', () {
      expect(
        checksumManifestUrlFor(direct),
        'https://github.com/fnthinklevi/noticeTransmit/releases/download/'
        'v1.6.7/sha256sums.txt',
      );
      expect(
        checksumManifestUrlFor(mirror),
        'https://xget.fnthink.top/gh/fnthinklevi/noticeTransmit/releases/download/'
        'v1.6.7/sha256sums.txt',
      );
    });

    test('URL 里编码过的 + 不会在换段时丢掉或变形', () {
      const encoded =
          'https://github.com/o/r/releases/download/v1.6.7/'
          'notice_arm64_1.6.7%2B167.apk';
      expect(
        checksumManifestUrlFor(encoded),
        'https://github.com/o/r/releases/download/v1.6.7/sha256sums.txt',
      );
    });

    test('不是可解析路径 ⇒ 不猜地址', () {
      expect(checksumManifestUrlFor(''), isNull);
      expect(checksumManifestUrlFor('not a url'), isNull);
    });
  });

  group('清单解析：按文件名取，取不到不猜', () {
    test('sha256sum 标准格式（两空格分隔）', () {
      final manifest =
          '$hash  notice_arm64_1.6.7+167.apk\n'
          '${'a' * 64}  notice_arm32_1.6.7+167.apk\n';
      expect(
        pickSha256ForAsset(
          manifest,
          assetName: 'notice_arm64_1.6.7+167.apk',
          abi: 'arm64',
        ),
        hash,
      );
    });

    test('二进制标记 * 与文件名前的目录都不影响匹配', () {
      const manifest = '$hash *build/notice_arm64_1.6.7+167.apk\n';
      expect(
        pickSha256ForAsset(manifest, assetName: 'notice_arm64_1.6.7+167.apk'),
        hash,
      );
    });

    test('大写哈希归一成小写（安装侧只比小写）', () {
      final manifest = '${hash.toUpperCase()}  notice_all_1.6.7+167.apk\n';
      expect(
        pickSha256ForAsset(manifest, assetName: 'notice_all_1.6.7+167.apk'),
        hash,
      );
    });

    test('文件名对不上时按 ABI 兜底（归档名与下载名不同的一档）', () {
      const manifest = '$hash  notice_arm64_1.6.7+167.apk\n';
      expect(
        pickSha256ForAsset(
          manifest,
          assetName: 'app-release.apk',
          abi: 'arm64',
        ),
        hash,
      );
    });

    test('清单里没有这一份 ⇒ null（调用方跳过 sha，不拿别人的哈希顶）', () {
      final manifest = '${'a' * 64}  notice_all_1.6.7+167.apk\n';
      expect(
        pickSha256ForAsset(
          manifest,
          assetName: 'notice_arm64_1.6.7+167.apk',
          abi: 'arm64',
        ),
        isNull,
      );
    });

    test('注释、空行、坏哈希只跳过那一行，不否定整份清单', () {
      const manifest =
          '# generated by CI\n'
          '\n'
          'not-a-hash  notice_arm64_1.6.7+167.apk\n'
          '$hash  notice_arm64_1.6.7+167.apk\n';
      expect(
        pickSha256ForAsset(manifest, assetName: 'notice_arm64_1.6.7+167.apk'),
        hash,
      );
    });
  });

  group('接线守卫：CI 产清单、客户端按来源选判据', () {
    test('CI 生成 sha256sums.txt 并随 artifact / Release 一起上传', () {
      final workflow = File('.github/workflows/build-apk.yml')
          .readAsStringSync();
      expect(workflow, contains(checksumManifestName));
      expect(workflow, contains('sha256sum '));
      expect(
        RegExp(r'upload-artifact[\s\S]{0,1200}?sha256sums\.txt')
            .hasMatch(workflow),
        isTrue,
        reason: 'artifact 里缺清单 ⇒ 事后无法复核这一版',
      );
      expect(
        RegExp(r'action-gh-release[\s\S]{0,1600}?sha256sums\.txt')
            .hasMatch(workflow),
        isTrue,
        reason: 'Release 里缺清单 ⇒ 客户端兜底时读不到',
      );
    });

    test('兜底下载不再拿 version.json 的 sha 判 GitHub 包', () {
      final source = File('lib/update_manager.dart').readAsStringSync();
      expect(source, contains('_lastDownloadUsedGithubFallback'));
      expect(source, contains('_fallbackExpectedSha256'));
      expect(source, contains('pickSha256ForAsset'));
      // 反证：旧写法是把 version.json 的 sha 无条件套到所有来源上
      expect(
        source,
        isNot(contains('final expected = sha256ByAbi[abi] ?? sha256ByAbi')),
        reason: '无条件套用 version.json 的 sha 就是这次要修的那条',
      );
    });
  });
}
